        var my = TableDdl.Build(DatabaseKind.MySql, Q, "s", "t", new TableChanges("t", []) { PrimaryKey = [], PrimaryKeyName = "PRIMARY" });
        Assert.Equal(["ALTER TABLE \"s\".\"t\" DROP PRIMARY KEY"], my);
    }

    [Fact]
    public void Comment_PerEngine_OnlyWhenChanged()
    {
        TableChanges Comment(string? old, string now) => new("t", []) { OldComment = old, Comment = now };
        Assert.Empty(TableDdl.Build(DatabaseKind.PostgreSql, Q, "s", "t", Comment("same", "same")));
        Assert.Equal("COMMENT ON TABLE \"s\".\"t\" IS 'it''s'", TableDdl.Build(DatabaseKind.PostgreSql, Q, "s", "t", Comment(null, "it's")).Single());
        Assert.Equal("COMMENT ON TABLE \"s\".\"t\" IS NULL", TableDdl.Build(DatabaseKind.PostgreSql, Q, "s", "t", Comment("x", "")).Single());
        Assert.Equal("ALTER TABLE \"s\".\"t\" COMMENT = 'a\\\\b'", TableDdl.Build(DatabaseKind.MySql, Q, "s", "t", Comment(null, "a\\b")).Single());
        Assert.StartsWith("EXEC sp_addextendedproperty N'MS_Description', N'x'", TableDdl.Build(DatabaseKind.SqlServer, B, "dbo", "t", Comment(null, "x")).Single());
        Assert.StartsWith("EXEC sp_updateextendedproperty", TableDdl.Build(DatabaseKind.SqlServer, B, "dbo", "t", Comment("o", "x")).Single());
        Assert.StartsWith("EXEC sp_dropextendedproperty", TableDdl.Build(DatabaseKind.SqlServer, B, "dbo", "t", Comment("o", "")).Single());
    }

    [Fact]
