    }

    [Fact]
    public void Columns_CommentsIdentityGeneratedCollation_PerEngine()
    {
        var old = new ColumnDef("a", "int", false, null) { Comment = "old" };
        var changes = new TableChanges("t", [new(old, old with { Comment = "new", AutoIncrement = true, Collation = "C" })]);
        Assert.Equal(
        [
            "ALTER TABLE \"s\".\"t\" ALTER COLUMN \"a\" TYPE int COLLATE \"C\" USING \"a\"::int",
            "ALTER TABLE \"s\".\"t\" ALTER COLUMN \"a\" ADD GENERATED BY DEFAULT AS IDENTITY",
            "COMMENT ON COLUMN \"s\".\"t\".\"a\" IS 'new'",
        ], TableDdl.Build(DatabaseKind.PostgreSql, Q, "s", "t", changes));
        Assert.Throws<NotSupportedException>(() => TableDdl.Build(DatabaseKind.SqlServer, B, "dbo", "t", changes));
        Assert.StartsWith("EXEC sp_updateextendedproperty N'MS_Description', N'new', N'SCHEMA', N'dbo', N'TABLE', N't', N'COLUMN', N'a'",
            TableDdl.Build(DatabaseKind.SqlServer, B, "dbo", "t", new TableChanges("t", [new(old, old with { Comment = "new" })])).Single());

        var total = new ColumnDef("total", "int", true, null) { Generated = "a * 2", Stored = true };
        string Add(DatabaseKind kind) => TableDdl.Build(kind, Q, "s", "t", new TableChanges("t", [new(null, total)])).Single();
        Assert.EndsWith("ADD COLUMN \"total\" int GENERATED ALWAYS AS (a * 2) STORED", Add(DatabaseKind.PostgreSql));
        Assert.EndsWith("ADD \"total\" AS (a * 2) PERSISTED", Add(DatabaseKind.SqlServer));
        Assert.EndsWith("\"total\" int GENERATED ALWAYS AS (a * 2) VIRTUAL",
            TableDdl.Build(DatabaseKind.MySql, Q, "s", "t", new TableChanges("t", [new(null, total with { Stored = false })])).Single());
        Assert.Throws<FormatException>(() => TableDdl.Build(DatabaseKind.MySql, Q, "s", "t",
            new TableChanges("t", [new(null, new ColumnDef("x", "text", true, null) { Collation = "bad; DROP" })])));
    }

    [Fact]
    public void Reorder_MySqlUsesAfter_PostgresRefuses()
    {
        var a = new ColumnDef("a", "int", true, null);
        var b = new ColumnDef("b", "int", true, null);
        var changes = new TableChanges("t", [new(b, b), new(null, a with { Name = "c" }), new(a, a)]) { Reordered = true };
        Assert.Equal(
        [
            "ALTER TABLE \"s\".\"t\" CHANGE COLUMN \"b\" \"b\" int FIRST",
            "ALTER TABLE \"s\".\"t\" ADD COLUMN \"c\" int AFTER \"b\"",
            "ALTER TABLE \"s\".\"t\" CHANGE COLUMN \"a\" \"a\" int AFTER \"c\"",
        ], TableDdl.Build(DatabaseKind.MySql, Q, "s", "t", changes));
        Assert.Throws<NotSupportedException>(() => TableDdl.Build(DatabaseKind.PostgreSql, Q, "s", "t", changes));
    }

    [Fact]
    public void Triggers_DroppedFirst_CreatedLast_OptionsAndChecks()
    {
        var sql = TableDdl.Build(DatabaseKind.MySql, Q, "s", "t", new TableChanges("t2", [])
        {
            DropTriggers = ["tr"], AddTriggers = ["CREATE TRIGGER tr2 BEFORE INSERT ON t2 FOR EACH ROW SET NEW.a = 1;"],
            Engine = "MyISAM", OldEngine = "InnoDB", Collation = "utf8mb4_bin", OldCollation = "utf8mb4_bin",
        });
        Assert.Equal(
        [
            "DROP TRIGGER \"s\".\"tr\"",
            "ALTER TABLE \"s\".\"t\" ENGINE = MyISAM",
            "RENAME TABLE \"s\".\"t\" TO \"s\".\"t2\"",
            "CREATE TRIGGER tr2 BEFORE INSERT ON t2 FOR EACH ROW SET NEW.a = 1",
        ], sql);
        Assert.Equal("DROP TRIGGER \"tr\" ON \"s\".\"t\"",
            TableDdl.Build(DatabaseKind.PostgreSql, Q, "s", "t", new TableChanges("t", []) { DropTriggers = ["tr"] }).Single());
        Assert.Equal("a > 0 AND (b < 1)", TableDdl.CheckExpression("CHECK ((a > 0 AND (b < 1)))"));
        Assert.Equal("(a > 0) OR (b < 1)", TableDdl.CheckExpression("CHECK ((a > 0) OR (b < 1)) NOT VALID"));
    }

    [Fact]
    public void CopyRows_KeepsIdentityValues()
    {
        IReadOnlyList<ColumnDef> columns = [new("id", "int", false, null) { AutoIncrement = true }, new("v", "int", true, null), new("g", "int", true, null) { Generated = "v * 2" }];
        Assert.Equal(
        [
            "SET IDENTITY_INSERT [s].[b] ON",
            "INSERT INTO [s].[b] ([id], [v]) SELECT [id], [v] FROM [s].[a]",
            "SET IDENTITY_INSERT [s].[b] OFF",
        ], TableDdl.CopyRows(DatabaseKind.SqlServer, B, "s", "a", "b", columns));
        Assert.Equal("SELECT setval(pg_get_serial_sequence('\"s\".\"b\"', 'id'), COALESCE(MAX(\"id\"), 0) + 1, false) FROM \"s\".\"b\"",
            TableDdl.CopyRows(DatabaseKind.PostgreSql, Q, "s", "a", "b", columns)[1]);
    }

    [Fact]
    public void Sqlite_TypeChange_RebuildsKeepingKeysChecksIndexesAndOptions()
    {
        var existing = new TableState(
            [new IndexInfo("PRIMARY KEY", ["id"], true, true, true), new IndexInfo("sqlite_autoindex_t_1", ["code"], true, false, true), new IndexInfo("ix", ["code"], false, false, false)],
            [new ForeignKey("0", ["parent"], "main", "p", [null]) { OnDelete = "CASCADE", OnUpdate = "NO ACTION" }],
            [new CheckConstraint("check", "CHECK (id > 0)")],
            [new TableObjectSql("table", "t", "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, code TEXT UNIQUE, parent INT REFERENCES p ON DELETE CASCADE, CHECK (id > 0)) STRICT"),
             new TableObjectSql("index", "ix", "CREATE INDEX ix ON t (code)")]);
        var id = new ColumnDef("id", "INTEGER", false, null) { AutoIncrement = true };
        var code = new ColumnDef("code", "TEXT", true, null);
        var parent = new ColumnDef("parent", "INT", true, null);

        var sql = TableDdl.Build(DatabaseKind.Sqlite, Q, "main", "t", new TableChanges("t",
            [new(id, id), new(code, code with { Name = "kode", IsNullable = false }), new(parent, null)])
        { Existing = existing, DropForeignKeys = [existing.ForeignKeys[0]] });

        Assert.Equal(
        [
            "PRAGMA defer_foreign_keys = ON",
            "CREATE TABLE \"main\".\"_qorra_new_t\" (\n    \"id\" INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT,\n    \"code\" TEXT NOT NULL,\n    UNIQUE (\"code\"),\n    CHECK (id > 0)\n) STRICT",
            "INSERT INTO \"main\".\"_qorra_new_t\" (\"id\", \"code\") SELECT \"id\", \"code\" FROM \"main\".\"t\"",
            "DROP TABLE \"main\".\"t\"",
            "PRAGMA legacy_alter_table = ON",
            "ALTER TABLE \"main\".\"_qorra_new_t\" RENAME TO \"t\"",
            "PRAGMA legacy_alter_table = OFF",
            "CREATE INDEX ix ON t (code)",
            "ALTER TABLE \"main\".\"t\" RENAME COLUMN \"code\" TO \"kode\"",
        ], sql);
    }
