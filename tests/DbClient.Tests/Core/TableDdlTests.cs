    [Fact]
    public void Postgres_EachKindOfChange_InOrder_TableRenameLast()
    {
        var sql = TableDdl.Build(DatabaseKind.PostgreSql, Q, "public", "t", new TableChanges("people",
        [
            new(Id, Id),
            new(Name, new ColumnDef("full_name", "text", false, null)),
            new(new ColumnDef("old", "int", true, null), null),
            new(null, new ColumnDef("age", "int", false, "0")),
        ])
        {
            DropIndexes = [new IndexInfo("ix", ["name"], false, false, false), new IndexInfo("uq", ["name"], true, false, true)],
            AddIndexes = [new NewIndex("ix2", ["age", " id "], true)],
            AddChecks = [new NewCheck("", "age >= 0")],
            AddForeignKeys = [new NewForeignKey("fk", ["age"], "public.ages", ["id"])],
        });

        Assert.Equal(
        [
            "DROP INDEX \"public\".\"ix\"",
            "ALTER TABLE \"public\".\"t\" DROP CONSTRAINT \"uq\"",
            "ALTER TABLE \"public\".\"t\" RENAME COLUMN \"name\" TO \"full_name\"",
            "ALTER TABLE \"public\".\"t\" ALTER COLUMN \"full_name\" TYPE text USING \"full_name\"::text",
            "ALTER TABLE \"public\".\"t\" ALTER COLUMN \"full_name\" SET NOT NULL",
            "ALTER TABLE \"public\".\"t\" ALTER COLUMN \"full_name\" DROP DEFAULT",
            "ALTER TABLE \"public\".\"t\" DROP COLUMN \"old\"",
            "ALTER TABLE \"public\".\"t\" ADD COLUMN \"age\" int NOT NULL DEFAULT 0",
            "CREATE UNIQUE INDEX \"ix2\" ON \"public\".\"t\" (\"age\", \"id\")",
            "ALTER TABLE \"public\".\"t\" ADD CHECK (age >= 0)",
            "ALTER TABLE \"public\".\"t\" ADD CONSTRAINT \"fk\" FOREIGN KEY (\"age\") REFERENCES public.ages (\"id\")",
            "ALTER TABLE \"public\".\"t\" RENAME TO \"people\"",
        ], sql);
    }

