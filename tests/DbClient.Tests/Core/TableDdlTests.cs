    [Fact]
    public void PrimaryKeyChange_DropsOldConstraintFirst_AddsNewAfterColumns()
    {
        var pg = TableDdl.Build(DatabaseKind.PostgreSql, Q, "s", "t", new TableChanges("t", [new(Id, Id), new(null, new ColumnDef("k", "int", false, null))])
            { PrimaryKey = ["id", "k"], PrimaryKeyName = "t_pkey" });
