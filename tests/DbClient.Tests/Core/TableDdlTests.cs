    private static string Q(string name) => "\"" + name + "\"";
    private static string B(string name) => "[" + name + "]";

    private static readonly ColumnDef Id = new("id", "integer", false, null);
    private static readonly ColumnDef Name = new("name", "varchar(40)", true, "'a'");

    [Fact]
    public void Create_ColumnsKeyConstraintsInline_ThenIndexesAndComment()
    {
        var sql = TableDdl.Create(DatabaseKind.PostgreSql, Q, "public", new TableChanges(" people ", [new(null, Id), new(null, Name)])
        {
            PrimaryKey = ["id"],
            AddChecks = [new NewCheck("", "id > 0")],
            AddForeignKeys = [new NewForeignKey("fk", ["id"], "public.ids", ["id"])],
            AddIndexes = [new NewIndex("ix", ["name"], false)],
            Comment = "it's",
        });

        Assert.Equal(
        [
            "CREATE TABLE \"public\".\"people\" (\n    \"id\" integer NOT NULL,\n    \"name\" varchar(40) DEFAULT 'a',\n    PRIMARY KEY (\"id\"),\n" +
            "    CHECK (id > 0),\n    CONSTRAINT \"fk\" FOREIGN KEY (\"id\") REFERENCES public.ids (\"id\")\n)",
            "CREATE INDEX \"ix\" ON \"public\".\"people\" (\"name\")",
            "COMMENT ON TABLE \"public\".\"people\" IS 'it''s'",
        ], sql);
        Assert.Throws<FormatException>(() => TableDdl.Create(DatabaseKind.PostgreSql, Q, "public", new TableChanges("t", [])));
    }

    [Theory]
    [InlineData(DatabaseKind.PostgreSql, "\"id\" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL")]
    [InlineData(DatabaseKind.SqlServer, "\"id\" bigint IDENTITY(1,1) NOT NULL")]
    [InlineData(DatabaseKind.MySql, "\"id\" bigint NOT NULL AUTO_INCREMENT")]
    public void Create_AutoIncrement_PerEngine(DatabaseKind kind, string column)
    {
        var id = new ColumnDef("id", "bigint", true, "1") { AutoIncrement = true };
        var sql = TableDdl.Create(kind, Q, "s", new TableChanges("t", [new(null, id)]) { PrimaryKey = ["id"] });
        Assert.Equal($"CREATE TABLE \"s\".\"t\" (\n    {column},\n    PRIMARY KEY (\"id\")\n)", sql[0]);
    }

