    [Fact]
    public void Indexes_MethodWhereDescending_PerEngine()
    {
        IReadOnlyList<string> Add(DatabaseKind kind, NewIndex index) =>
            TableDdl.Build(kind, Q, "s", "t", new TableChanges("t", []) { AddIndexes = [index] });
        var partial = new NewIndex("ix", ["a DESC", "b"], false) { Method = "gin", Where = "a > 0" };
        Assert.Equal("CREATE INDEX \"ix\" ON \"s\".\"t\" USING gin (\"a\" DESC, \"b\") WHERE a > 0", Add(DatabaseKind.PostgreSql, partial).Single());
        Assert.Equal("CREATE INDEX \"ix\" ON \"s\".\"t\" (lower(a))", Add(DatabaseKind.PostgreSql, new NewIndex("ix", ["lower(a)"], false) { Method = "btree" }).Single());
        Assert.Equal("CREATE INDEX \"ix\" ON \"s\".\"t\" (\"a\") USING HASH", Add(DatabaseKind.MySql, new NewIndex("ix", ["a"], false) { Method = "HASH" }).Single());
        Assert.Equal("CREATE FULLTEXT INDEX \"ix\" ON \"s\".\"t\" (\"a\")", Add(DatabaseKind.MySql, new NewIndex("ix", ["a"], false) { Method = "fulltext" }).Single());
        Assert.Throws<NotSupportedException>(() => Add(DatabaseKind.MySql, partial with { Method = null }));
        Assert.Equal("CREATE UNIQUE CLUSTERED INDEX ix ON s.t (a) WHERE a > 0",
            Add(DatabaseKind.SqlServer, new NewIndex("ix", ["a"], true) { Method = "CLUSTERED", Where = "a > 0" }).Single().Replace("\"", ""));
    }

    [Fact]
