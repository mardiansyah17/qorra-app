    [Fact]
    public void SqlServer_RenamesWithSpRename_AndReplacesDefaultConstraint()
    {
        var sql = TableDdl.Build(DatabaseKind.SqlServer, B, "dbo", "t", new TableChanges("o'k",
        [
            new(Name, new ColumnDef("nm", "nvarchar(50)", true, "'b'")),
            new(null, new ColumnDef("n", "int", true, null)),
        ]));

        Assert.Equal("EXEC sp_rename N'[dbo].[t].[name]', N'nm', 'COLUMN'", sql[0]);
        Assert.Contains("sys.default_constraints", sql[1]);
        Assert.Contains("N'nm'", sql[1]);
        Assert.Equal("ALTER TABLE [dbo].[t] ALTER COLUMN [nm] nvarchar(50) NULL", sql[2]);
        Assert.Equal("ALTER TABLE [dbo].[t] ADD DEFAULT 'b' FOR [nm]", sql[3]);
        Assert.Equal("ALTER TABLE [dbo].[t] ADD [n] int NULL", sql[4]);
        Assert.Equal("EXEC sp_rename N'[dbo].[t]', N'o''k'", sql[5]);
    }

